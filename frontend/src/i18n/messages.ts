export function normalizeUiLanguage(value: string | null | undefined): UiLanguage {
  return SUPPORTED_UI_LANGUAGES.includes(value as UiLanguage) ? value as UiLanguage : 'ko'
}

export function formatMessage(template: string, values: Record<string, string | number>) {
  return Object.entries(values).reduce(
    (text, [key, value]) => text.replaceAll(`{${key}}`, String(value)),
    template,
  )
}

export function languageDisplayName(code: string, uiLanguage: UiLanguage) {
  try {
    return new Intl.DisplayNames([uiLanguage], { type: 'language' }).of(code) ?? code
  } catch {
    return code
  }
}

